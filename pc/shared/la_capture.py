#!/usr/bin/env python3
# la_capture.py — sigrok-cli integration for the opt-in `--la` flag on the Uno
# Phase 2 sweep (pc/phase2_sweep/uno_sweep.py). Arms a capture before the board
# is reflashed (so it is armed strictly before the "run" — the upload/reset
# that starts the device pulsing GPIO_TIMING_PIN), stops it after the point
# finishes, and runs the existing analysis/la_pulses.py + analysis/la_crosscheck.py
# on the result.
#
# *** sigrok-cli command lines below are UNVERIFIED — sigrok-cli has never been
# run against real hardware (or even its `demo` driver) in this environment.
# See run_checklist.md "sigrok-cli command lines — UNVERIFIED" for the same
# caveat and the exact templates these are built from. Confirm flag names
# against `sigrok-cli --help` / `sigrok-cli -O csv:help` before trusting this
# on a real point. ***
#
# A capture problem (missing sigrok, scan finds no device, pulse count
# mismatch, truncated capture, sigrok error) is logged to this circuit's own
# la/capture_issues.log (LA_DIR/ISSUES_LOG below, reassigned per (board,
# circuit) by the caller before each circuit's sweep — see pc/shared/paths.py
# and uno_sweep.py's _run_circuit, 2026-09-20 layout change) and MUST NOT
# affect the point's micros() data or its status in memory_wall.csv /
# points.csv / sessions.csv — those files are written by the caller exactly
# as they would be with --la off.

import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(REPO_ROOT / "analysis"))

# Module-level fallback only (e.g. for direct/manual use or tests) -- every
# sweep script reassigns these three per circuit before using la_capture at
# all, since captures now live under that circuit's own la/ dir, not one
# shared global directory.
LA_DIR = REPO_ROOT / "data" / "raw" / "la"
PLAN_PATH = LA_DIR / "capture_plan.csv"
ISSUES_LOG = LA_DIR / "capture_issues.log"

SIGROK_BIN = "sigrok-cli"
MARGIN = 1.5           # safety margin over the expected capture duration
FIXED_PAD_S = 0.5      # fixed pad on top of the margin, for short pulses
ARM_CONFIRM_S = 0.3    # brief wait to confirm the process didn't die immediately


def log_issue(board: str, circuit: str, n: int, message: str) -> None:
    """Append one line to this circuit's la/capture_issues.log (module-level
    ISSUES_LOG, reassigned per circuit by the caller). Never raises — a
    logging failure must not take down the sweep. This file is additive only;
    it is not part of the frozen telemetry schema and nothing reads it back
    to make pass/fail decisions."""
    try:
        LA_DIR.mkdir(parents=True, exist_ok=True)
        ts = datetime.now(timezone.utc).isoformat()
        with open(ISSUES_LOG, "a") as f:
            f.write(f"{ts}  {board}/{circuit}/n={n}  {message}\n")
    except OSError as e:
        print(f"la_capture: could not write to {ISSUES_LOG}: {e}", file=sys.stderr)


def check_sigrok():
    """`which sigrok-cli` + `sigrok-cli --scan`. Returns a dict:
    {available: bool, driver: str|None, note: str}
    Never raises — any failure here means "continue without capture", not a
    crash (see run_checklist.md § Logic Analyzer procedure, B3)."""
    path = shutil.which(SIGROK_BIN)
    if not path:
        return {"available": False, "driver": None,
                "note": f"{SIGROK_BIN} not found on PATH"}
    try:
        proc = subprocess.run([SIGROK_BIN, "--scan"], capture_output=True,
                               text=True, timeout=15)
    except (subprocess.TimeoutExpired, OSError) as e:
        return {"available": False, "driver": None,
                "note": f"{SIGROK_BIN} --scan failed to run: {e}"}
    out = (proc.stdout or "") + (proc.stderr or "")
    if proc.returncode != 0:
        return {"available": False, "driver": None,
                "note": f"{SIGROK_BIN} --scan exited {proc.returncode}: {out[-500:]}"}
    # UNVERIFIED: real --scan output format has never been seen. We only know
    # "no device" looks like an empty/near-empty listing; do not guess a
    # driver name out of the text, that is a real LA-model-specific string
    # per run_checklist.md ("don't guess from the device's marketing name").
    if not out.strip():
        return {"available": False, "driver": None,
                "note": f"{SIGROK_BIN} --scan found no device"}
    return {"available": True, "driver": None,
            "note": f"{SIGROK_BIN} --scan found a device — UNVERIFIED: driver "
                     "string not auto-parsed, confirm manually against the "
                     "--scan output before trusting a real capture"}


def load_plan_entry(board: str, circuit: str, n: int, plan_path: Path = None):
    """Look up (n_reps_to_capture, recommended_sample_rate_hz) for one point
    from <this circuit's la dir>/capture_plan.csv (generated by
    analysis/la_capture_plan.py). Returns None if the plan file doesn't exist
    or has no row for this point — callers must not guess a rate/rep-count in
    that case, per run_checklist.md's "generate the capture plan first" rule.

    plan_path=None resolves to module-level PLAN_PATH "at call time", not at
    def time — a bound default (`plan_path: Path = PLAN_PATH` directly) would
    freeze whatever PLAN_PATH was when this function was defined/module-
    loaded, so reassigning `la_capture.PLAN_PATH` later (as every sweep script
    now does per algorithm, and as tests do to redirect into a scratch dir)
    would silently have no effect on calls that don't pass plan_path
    explicitly. Same bug class telemetry.py's write_point_row docstring
    documents finding and fixing — found latent here 2026-09-20 during the
    per-board-per-algorithm path migration, before it had ever mattered in
    practice (--la has never been run against real hardware)."""
    if plan_path is None:
        plan_path = PLAN_PATH
    if not plan_path.exists():
        return None
    import csv
    with open(plan_path, newline="") as f:
        for row in csv.DictReader(f):
            if row["board"] == board and row["circuit"] == circuit and int(row["n"]) == n:
                return {
                    "n_reps_to_capture": int(row["n_reps_to_capture"]),
                    "recommended_sample_rate_hz": float(row["recommended_sample_rate_hz"]),
                }
    return None


def _expected_reduced(board, circuit, n, plan_entry):
    """Best-effort expected duration (s) for however many reps this capture
    is meant to cover, used only to size the (UNVERIFIED) sigrok-cli
    invocation with a margin — never used to judge pass/fail."""
    sys.path.insert(0, str(REPO_ROOT / "pc"))
    from shared import timing_model as tm  # noqa: E402
    reps = plan_entry["n_reps_to_capture"]
    per_rep_s = tm.expected_exec_time_us(board, circuit, n) / 1e6
    return per_rep_s * reps


class ArmedCapture:
    """Handle for one armed-but-not-yet-stopped capture."""

    def __init__(self, proc, out_path: Path, reduced: bool, hold_s: float):
        self.proc = proc
        self.out_path = out_path
        self.reduced = reduced
        self.hold_s = hold_s  # for reduced captures: how long to let it run before stopping


def arm_capture(board: str, circuit: str, n: int, plan_entry: dict, out_path: Path):
    """Start the sigrok-cli subprocess BEFORE the board is reflashed, so it is
    armed strictly before the run starts. Returns an ArmedCapture on success,
    or None on failure (logged via log_issue by the caller).

    Does not block the timed region: this only starts a background process
    and confirms it is still alive a moment later — it runs entirely on the
    PC side, outside anything the firmware's GPIO pulse or micros() window
    brackets."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    reps = plan_entry["n_reps_to_capture"]
    rate_hz = plan_entry["recommended_sample_rate_hz"]
    reduced = reps < 100  # REPS default; capture_plan.py only reduces below full REPS

    expected_s = _expected_reduced(board, circuit, n, plan_entry)
    duration_with_margin = expected_s * MARGIN + FIXED_PAD_S

    if reduced:
        # UNVERIFIED — mirrors run_checklist.md's reduced-rep template: free-run
        # and stop manually rather than trust --samples/--time to land exactly
        # on the Nth pulse.
        cmd = [SIGROK_BIN, "--config", f"samplerate={rate_hz:.0f}",
               "--triggers", "D0=r", "--continuous",
               "-O", "csv", "-o", str(out_path)]
        hold_s = duration_with_margin
    else:
        samples = max(1, int(rate_hz * duration_with_margin))
        # UNVERIFIED — mirrors run_checklist.md's full-rate/full-reps template.
        cmd = [SIGROK_BIN, "--config", f"samplerate={rate_hz:.0f}",
               "--triggers", "D0=r", "--samples", str(samples),
               "-O", "csv", "-o", str(out_path)]
        hold_s = None

    try:
        proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                 text=True)
    except OSError as e:
        log_issue(board, circuit, n, f"sigrok-cli failed to start: {e}")
        return None

    time.sleep(ARM_CONFIRM_S)
    if proc.poll() is not None:
        _, stderr = proc.communicate()
        log_issue(board, circuit, n,
                   f"sigrok-cli exited immediately (rc={proc.returncode}): {stderr[-500:]}")
        return None

    return ArmedCapture(proc, out_path, reduced, hold_s)


def stop_capture(armed: ArmedCapture, board: str, circuit: str, n: int, timeout_s: float = 15.0):
    """Stop/finish the capture after the point completes. Returns True if the
    capture file looks like it was produced without an obvious sigrok error;
    any problem is logged, never raised — the caller's micros() data must be
    written regardless of what happens here."""
    proc = armed.proc
    try:
        if armed.reduced:
            # Reduced-rep point: firmware still ran all 100 reps on-device
            # (unmodified), but we only want the first n_reps_to_capture
            # pulses per run_checklist.md's reduced-capture procedure — the
            # automated stand-in for "watch the trace and Ctrl-C after ~5
            # pulses": hold for the estimated duration, then stop.
            remaining = armed.hold_s - ARM_CONFIRM_S
            if remaining > 0:
                time.sleep(remaining)
            proc.terminate()
        # else: --samples run should already be finishing on its own; still
        # wait it out below with a hard timeout in case sigrok hangs.
        try:
            _, stderr = proc.communicate(timeout=timeout_s)
        except subprocess.TimeoutExpired:
            proc.kill()
            _, stderr = proc.communicate()
            log_issue(board, circuit, n, "sigrok-cli did not exit on its own, killed after timeout")
            return False

        if proc.returncode not in (0, None) and proc.returncode < 0:
            # negative = killed by our own terminate()/SIGTERM for a reduced
            # capture, which is expected, not an error
            pass
        elif proc.returncode not in (0,):
            log_issue(board, circuit, n,
                       f"sigrok-cli exited with rc={proc.returncode}: {(stderr or '')[-500:]}")
            return False

        if not armed.out_path.exists() or armed.out_path.stat().st_size == 0:
            log_issue(board, circuit, n, f"capture file missing or empty: {armed.out_path}")
            return False
        return True
    except Exception as e:  # sigrok integration is best-effort; never crash the sweep
        log_issue(board, circuit, n, f"unexpected error stopping capture: {e}")
        return False


def run_analysis(board: str, circuit: str, n: int, capture_path: Path, expected_reps: int):
    """Run analysis/la_pulses.py and analysis/la_crosscheck.py on one capture
    file. Any non-clean result (pulse count mismatch, truncation, glitch,
    parse error) is logged via log_issue and returned as ok=False — it never
    raises and never touches the point's micros() data."""
    py = sys.executable
    la_pulses = REPO_ROOT / "analysis" / "la_pulses.py"
    la_crosscheck = REPO_ROOT / "analysis" / "la_crosscheck.py"

    try:
        proc = subprocess.run([py, str(la_pulses), str(capture_path),
                                "--expected-reps", str(expected_reps)],
                               capture_output=True, text=True, timeout=120)
    except (subprocess.TimeoutExpired, OSError) as e:
        log_issue(board, circuit, n, f"la_pulses.py failed to run: {e}")
        return {"ok": False}

    out = proc.stdout
    is_clean = "is_clean (safe to join by sequence order): True" in out
    if proc.returncode != 0 or not is_clean:
        log_issue(board, circuit, n,
                   f"la_pulses.py reported a problem (rc={proc.returncode}, "
                   f"is_clean={is_clean}): {out[-800:]} {proc.stderr[-500:]}")

    try:
        cc_proc = subprocess.run([py, str(la_crosscheck), "--expected-reps", str(expected_reps)],
                                  capture_output=True, text=True, timeout=120)
        if cc_proc.returncode != 0:
            log_issue(board, circuit, n,
                       f"la_crosscheck.py exited {cc_proc.returncode}: {cc_proc.stderr[-500:]}")
    except (subprocess.TimeoutExpired, OSError) as e:
        log_issue(board, circuit, n, f"la_crosscheck.py failed to run: {e}")

    return {"ok": proc.returncode == 0 and is_clean, "la_pulses_stdout": out}
