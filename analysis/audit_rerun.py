"""Repeat-measurement audit (read-only on data/raw). Writes data/derived/rerun_sessions.csv and docs/audit/rerun_sessions.md.

A repeat session lives in data/raw/phase<N>/<board>/<circuit>/with_ref_<TAG>/ (pc/run.py --rerun TAG). It is a whole new sample per point and
is never merged into with_ref/. Per (bucket, n): reps, median of the board's own timer in the repeat and in the original, their ratio,
the counter pairing status and usable pairs of the repeat, and whether the firmware source hash is the same as the original's.
Phase 2 timer column: exec_time_us (memory_wall.csv terminal record). Phase 3: e2e_latency_us (session_log.csv terminal record).
"""
import csv
import glob
import json
import os
import statistics

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RAW = os.path.join(ROOT, "data", "raw")
OUT_CSV = os.path.join(ROOT, "data", "derived", "rerun_sessions.csv")
OUT_MD = os.path.join(ROOT, "docs", "audit", "rerun_sessions.md")


def rows(path):
    return list(csv.DictReader(open(path, newline=""))) if os.path.exists(path) else []


def hashes(base):
    out = set()
    for f in glob.glob(os.path.join(base, "env", "*.json")):
        if not f.endswith(".ref.json"):
            out.add(json.load(open(f)).get("firmware_source_hash", "?"))
    return sorted(out)


def medians(base, phase):
    col = "exec_time_us" if phase == 2 else "e2e_latency_us"
    by = {}
    for r in rows(os.path.join(base, "raw.csv")):
        try:
            by.setdefault(int(r["n"]), []).append(float(r[col]))
        except (KeyError, ValueError):
            pass
    return {n: (len(v), statistics.median(v)) for n, v in by.items()}


def terminal(base, phase):
    f = "memory_wall.csv" if phase == 2 else "session_log.csv"
    return {int(r["n"]): r["status"] for r in rows(os.path.join(base, f)) if r.get("n")}


def main():
    out = []
    for rb in sorted(glob.glob(os.path.join(RAW, "phase[23]", "*", "*", "with_ref_*"))):
        parts = rb.split(os.sep)
        phase, board, circuit, bucket = int(parts[-4][-1]), parts[-3], parts[-2], parts[-1]
        orig = os.path.join(os.path.dirname(rb), "with_ref")
        mr, mo = medians(rb, phase), medians(orig, phase)
        st = terminal(rb, phase)
        ref = {int(r["n"]): r for r in rows(os.path.join(rb, "ref", "ref_compare_points.csv"))}
        same_hash = hashes(rb) == hashes(orig)
        for n in sorted(st):
            nr, med = mr.get(n, (0, float("nan")))
            no, med0 = mo.get(n, (0, float("nan")))
            r = ref.get(n, {})
            out.append(dict(phase=phase, board=board, circuit=circuit, bucket=bucket, n=n, status=st[n], reps=nr,
                            median_repeat=round(med, 3), reps_original=no, median_original=round(med0, 3) if no else "",
                            ratio_repeat_over_original=round(med / med0, 6) if no and med0 else "",
                            counter_pairs=r.get("n_pairs", ""), counter_status=r.get("ref_status", ""),
                            firmware_hash_same_as_original=same_hash))
    os.makedirs(os.path.dirname(OUT_CSV), exist_ok=True)
    cols = list(out[0].keys()) if out else []
    with open(OUT_CSV, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(out)
    lines = ["# Repeat sessions (--rerun)", "",
             "Generated by `analysis/audit_rerun.py` from `data/raw/phase*/*/*/with_ref_<TAG>/` (read-only). A repeat is a whole new sample per point,",
             "never merged into `with_ref/`. Timer = `exec_time_us` (Phase 2) or `e2e_latency_us` (Phase 3). `counter` = usable pairs / status.", "",
             "| phase | board | circuit | bucket | n | status | reps | median repeat | median original | ratio | counter | same fw hash |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in out:
        lines.append(f"| {r['phase']} | {r['board']} | {r['circuit']} | {r['bucket']} | {r['n']} | {r['status']} | {r['reps']} | {r['median_repeat']} | "
                     f"{r['median_original'] if r['median_original'] != '' else '-'} | {r['ratio_repeat_over_original'] if r['ratio_repeat_over_original'] != '' else '-'} | "
                     f"{r['counter_pairs'] or '-'} {r['counter_status']} | {r['firmware_hash_same_as_original']} |")
    open(OUT_MD, "w").write("\n".join(lines) + "\n")
    print(f"{len(out)} repeat points -> {os.path.relpath(OUT_CSV, ROOT)}, {os.path.relpath(OUT_MD, ROOT)}")


if __name__ == "__main__":
    main()
