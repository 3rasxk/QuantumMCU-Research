"""Item 7b: provenance of every collected session (Phase 2 and Phase 3, all circuits). Writes data/derived/session_provenance.csv and
docs/reproducibility/session_provenance.md.

Columns: session, phase, board, circuit, start_utc, git_commit (recorded at run time), git_dirty (recorded), firmware_source_hash,
hash_in_git (the hash equals the firmware tree of some commit, see firmware_hash_commits.csv), tree_at_recorded_commit_matches (hash equals
the firmware tree of the commit the session recorded), binary_hash_recorded (always no: no session stores a hash of the flashed binary),
source_hash_identifies_code.
'Source hash identifies the code' = yes only when the hash equals a committed firmware tree (the exact source text can then be recovered
from git). It never identifies the binary: the binary also depends on the PlatformIO toolchain (recorded per session as pio_packages), on the
per-point -D flags (N_QUBITS, CIRCUIT_ID, BAUD_RATE, REPS, RESPONSE_TIMEOUT_MS) and on no file hashing at all; dirty = uncommitted changes at run time.
"""
import glob
import json
import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "analysis"))
import audit_data as A  # noqa: E402

RAW = os.path.join(ROOT, "data", "raw")


def main():
    sc_path = os.path.join(ROOT, "data", "derived", "firmware_hash_commits.csv")
    sc = pd.read_csv(sc_path)
    in_git = {(r.board, r.phase, r.hash): bool(r.in_git) for r in sc.itertuples()}
    rows = []
    # one row per session env JSON (60 on disk); sessions.csv has fewer rows (a resumed or interrupted session may not write one)
    for ep in sorted(glob.glob(os.path.join(RAW, "phase*", "*", "*", "with_ref*", "env", "*.json"))):
        if ep.endswith(".ref.json"):
            continue
        parts = ep.split(os.sep)
        ph, b, c = int(parts[-6].replace("phase", "")), parts[-5], parts[-4]
        e = json.load(open(ep))
        h = e.get("firmware_source_hash", "")
        commit = e.get("git_commit", "")
        tree_hash = A.fw_hash_commit(ROOT, commit, b, ph) if commit else None
        match = None if tree_hash is None else (tree_hash == h)          # None = not decidable (no git history available), never False
        rows.append(dict(session=e.get("session_id"), phase=ph, board=b, circuit=c, start_utc=e.get("recorded_utc"), git_commit=commit[:10],
                         git_dirty=e.get("git_dirty"), firmware_source_hash=h, hash_in_git=in_git.get((b, ph, h), False),
                         tree_at_recorded_commit_matches=match, binary_hash_recorded="no", pio_env=e.get("pio_env"),
                         platformio=e.get("platformio_version"),
                         toolchain=";".join(f"{k}={v}" for k, v in (e.get("pio_packages") or {}).items()
                                            if k.startswith("toolchain") or k.startswith("framework"))))
    df = pd.DataFrame(rows).sort_values(["phase", "board", "circuit", "start_utc"]).reset_index(drop=True)
    df["source_hash_identifies_code"] = df.hash_in_git.map({True: "yes (equals a committed firmware tree)", False: "no (uncommitted working tree; source not in git)"})
    df.to_csv(os.path.join(ROOT, "data", "derived", "session_provenance.csv"), index=False)
    os.makedirs(os.path.join(ROOT, "docs", "reproducibility"), exist_ok=True)
    cols = ["session", "phase", "board", "circuit", "git_commit", "git_dirty", "firmware_source_hash", "hash_in_git", "tree_at_recorded_commit_matches", "binary_hash_recorded"]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for _, r in df.iterrows()]
    n_in, n_dirty = int(df.hash_in_git.sum()), int(df.git_dirty.fillna(True).astype(bool).sum())
    head = (f"# Session provenance ({len(df)} sessions)\n\nGenerated by `analysis/phase4/provenance.py` from the session env JSON files and "
            f"`data/derived/firmware_hash_commits.csv`. {n_dirty} of {len(df)} sessions were recorded with a dirty working tree "
            f"(`git status --porcelain` also counts untracked data files, so the flag alone does not show that firmware changed). "
            f"{n_in} sessions have a source hash equal to a committed firmware tree; {len(df) - n_in} do not (uncommitted source at run time). "
            "**No session records a hash of the flashed binary**, so the binary is not identified by any recorded value; the recorded source hash identifies "
            "the source text only when it equals a committed tree.\n\n")
    open(os.path.join(ROOT, "docs", "reproducibility", "session_provenance.md"), "w").write(head + "\n".join(lines) + "\n")
    write_environment(df)
    return df


def write_environment(df):
    """docs/reproducibility/environment.md: host, Python, pip freeze of the interpreter that ran the analysis, PlatformIO and toolchains per board
    as recorded by the sessions themselves (env JSON)."""
    import subprocess
    envs = {}
    for f in glob.glob(os.path.join(RAW, "phase*", "*", "*", "with_ref*", "env", "*.json")):
        if f.endswith(".ref.json"):
            continue
        e = json.load(open(f))
        key = (e.get("board"), e.get("pio_env"), e.get("platformio_version"), e.get("host_os"), e.get("python_version"))
        envs.setdefault(key, {"pk": e.get("pio_packages") or {}, "n": 0})["n"] += 1
    lines = ["# Environment used to collect and analyse the data\n",
             "Recorded by the sessions themselves (`data/raw/**/env/*.json`); one row per distinct (board, PlatformIO env, PlatformIO, host, Python).\n",
             "| board | pio env | PlatformIO | host OS | Python | sessions | toolchain and framework packages |", "|---|---|---|---|---|---|---|"]
    for (b, pe, pio, host, py), v in sorted(envs.items(), key=lambda x: str(x[0])):
        pk = "; ".join(f"{k} {x}" for k, x in v["pk"].items() if k.startswith(("toolchain-", "framework-", "platform")) and "esptool" not in k)
        lines.append(f"| {b} | {pe} | {pio} | {host} | {py} | {v['n']} | {pk} |")
    freeze = subprocess.run([sys.executable, "-m", "pip", "freeze"], capture_output=True, text=True).stdout
    lines += ["", f"## pip freeze of the interpreter used for the analysis (`{sys.version.split()[0]}`)", "", "```", freeze.strip(), "```", ""]
    open(os.path.join(ROOT, "docs", "reproducibility", "environment.md"), "w").write("\n".join(lines))


if __name__ == "__main__":
    d = main()
    print(len(d), "sessions;", int(d.hash_in_git.sum()), "with hash in git;", int(d.git_dirty.fillna(True).astype(bool).sum()), "dirty")
